create or replace function private.current_pos_org_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select p.organization_id
  from public.pos_profiles p
  where p.user_id = (select auth.uid())
    and p.is_active = true
  limit 1
$$;

create or replace function private.pos_has_role(allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.pos_profiles p
    where p.user_id = (select auth.uid())
      and p.is_active = true
      and p.role = any(allowed_roles)
  )
$$;

revoke all on function private.current_pos_org_id() from public, anon;
revoke all on function private.pos_has_role(text[]) from public, anon;
grant usage on schema private to authenticated;
grant execute on function private.current_pos_org_id() to authenticated;
grant execute on function private.pos_has_role(text[]) to authenticated;

create or replace function private.pos_touch_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

