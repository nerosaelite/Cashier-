create or replace view public.pos_daily_sales
with (security_invoker = true)
as
select
  organization_id,
  sold_at::date as sale_date,
  count(*) as invoices,
  coalesce(sum(total), 0) as total_sales,
  coalesce(sum(paid), 0) as total_paid,
  coalesce(sum(due), 0) as total_due,
  coalesce(sum(discount), 0) as total_discount
from public.pos_sales
where status = 'completed'
group by organization_id, sold_at::date;

drop view if exists public.pos_customer_balances;
create view public.pos_customer_balances
with (security_invoker = true)
as
select
  c.id as customer_id,
  c.organization_id,
  c.name,
  c.phone,
  c.opening_balance + coalesce(sum(
    (case when a.direction = 'debit' then a.amount else -a.amount end)
    * case
        when a.currency = o.default_currency then 1
        when a.currency = 'USD' then o.exchange_rate
        else 1 / o.exchange_rate
      end
  ), 0) as balance
from public.pos_customers c
join public.pos_organizations o on o.id = c.organization_id
left join public.pos_account_entries a
  on a.organization_id = c.organization_id
  and a.party_type = 'customer'
  and a.party_id = c.id
group by c.id, c.organization_id, c.name, c.phone, c.opening_balance, o.default_currency, o.exchange_rate;

