  p_first_due date default null,
  p_notes text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  org_id bigint := (select private.current_pos_org_id());
  sale_id bigint;
  invoice_no text;
  subtotal_value numeric(14,3) := 0;
  total_value numeric(14,3);
  paid_value numeric(14,3);
  due_value numeric(14,3);
  item jsonb;
  product_row public.pos_products%rowtype;
  qty numeric(14,3);
  price_value numeric(14,3);
  each_installment numeric(14,3);
  i integer;
begin
  if org_id is null then raise exception 'الحساب غير مربوط بالشركة'; end if;
  if p_sale_type not in ('retail','wholesale','credit','installment') then raise exception 'نوع البيع غير صحيح'; end if;
  if p_currency not in ('IQD','USD') then raise exception 'العملة غير صحيحة'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'السلة فارغة'; end if;

  insert into public.pos_sales(organization_id, customer_id, sale_type, currency, discount, paid, notes, created_by)
  values (org_id, p_customer_id, p_sale_type, p_currency, greatest(coalesce(p_discount,0),0), 0, p_notes, (select auth.uid()))
  returning id into sale_id;

  for item in select value from jsonb_array_elements(p_items) loop
    qty := coalesce((item ->> 'quantity')::numeric, 0);
    if qty <= 0 then raise exception 'الكمية غير صحيحة'; end if;
    select * into product_row from public.pos_products
    where id = (item ->> 'product_id')::bigint and organization_id = org_id and is_active = true
    for update;
    if not found then raise exception 'المنتج غير موجود'; end if;
    if product_row.stock < qty then raise exception 'المخزون غير كافٍ للمنتج %', product_row.name; end if;
    price_value := coalesce(nullif(item ->> 'unit_price','')::numeric,
      case when p_sale_type = 'wholesale' then product_row.wholesale_price else product_row.retail_price end);
    if price_value < 0 then raise exception 'السعر غير صحيح'; end if;

    insert into public.pos_sale_items(organization_id, sale_id, product_id, product_name, barcode, quantity, unit_price)
    values (org_id, sale_id, product_row.id, product_row.name, product_row.barcode, qty, price_value);
    update public.pos_products set stock = stock - qty where id = product_row.id;
    insert into public.pos_stock_movements(organization_id, product_id, movement_type, quantity, reference_type, reference_id, created_by)
    values (org_id, product_row.id, 'sale', -qty, 'sale', sale_id, (select auth.uid()));
    subtotal_value := subtotal_value + (qty * price_value);
  end loop;

  total_value := greatest(subtotal_value - greatest(coalesce(p_discount,0),0), 0);
  paid_value := least(greatest(coalesce(p_paid,0),0), total_value);
  due_value := total_value - paid_value;
  if due_value > 0 and p_customer_id is null then raise exception 'اختر العميل للبيع الآجل أو القسط'; end if;
  invoice_no := 'NER-S-' || to_char(current_date, 'YYYYMMDD') || '-' || lpad(sale_id::text, 6, '0');
  update public.pos_sales set invoice_number = invoice_no, subtotal = subtotal_value, total = total_value, paid = paid_value where id = sale_id;

  if p_customer_id is not null then
    insert into public.pos_account_entries(organization_id, party_type, party_id, entry_type, direction, amount, currency, reference_type, reference_id, notes, created_by)
    values (org_id, 'customer', p_customer_id, 'sale', 'debit', total_value, p_currency, 'sale', sale_id, invoice_no, (select auth.uid()));
    if paid_value > 0 then
      insert into public.pos_account_entries(organization_id, party_type, party_id, entry_type, direction, amount, currency, reference_type, reference_id, notes, created_by)
      values (org_id, 'customer', p_customer_id, 'sale_payment', 'credit', paid_value, p_currency, 'sale', sale_id, invoice_no, (select auth.uid()));
    end if;
  end if;

  if p_sale_type = 'installment' and due_value > 0 and p_installment_count > 0 then
    each_installment := round(due_value / p_installment_count, 3);
    for i in 1..p_installment_count loop
      insert into public.pos_installments(organization_id, sale_id, customer_id, installment_number, due_date, amount)
      values (
        org_id, sale_id, p_customer_id, i,
        coalesce(p_first_due, current_date + interval '1 month')::date + ((i - 1) * interval '1 month'),
        case when i = p_installment_count then due_value - (each_installment * (p_installment_count - 1)) else each_installment end
      );
    end loop;
  end if;

  insert into public.pos_audit_logs(organization_id, user_id, action, entity_type, entity_id, details)
  values (org_id, (select auth.uid()), 'create_sale', 'sale', sale_id, jsonb_build_object('invoice', invoice_no, 'total', total_value));
  return jsonb_build_object('id', sale_id, 'invoice_number', invoice_no, 'subtotal', subtotal_value, 'total', total_value, 'paid', paid_value, 'due', due_value);
end;
$$;

create or replace function public.pos_create_purchase(
  p_supplier_id bigint,
  p_supplier_invoice text,
  p_currency text,
  p_discount numeric,
  p_paid numeric,
  p_items jsonb,
  p_notes text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  org_id bigint := (select private.current_pos_org_id());
  purchase_id bigint;
  invoice_no text;
  subtotal_value numeric(14,3) := 0;
  total_value numeric(14,3);
  paid_value numeric(14,3);
  item jsonb;
  product_row public.pos_products%rowtype;
  qty numeric(14,3);
  cost_value numeric(14,3);
begin
  if org_id is null then raise exception 'الحساب غير مربوط بالشركة'; end if;
  if p_currency not in ('IQD','USD') then raise exception 'العملة غير صحيحة'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'قائمة المشتريات فارغة'; end if;

  insert into public.pos_purchases(organization_id, supplier_id, supplier_invoice, currency, discount, notes, created_by)
  values (org_id, p_supplier_id, p_supplier_invoice, p_currency, greatest(coalesce(p_discount,0),0), p_notes, (select auth.uid()))
  returning id into purchase_id;

  for item in select value from jsonb_array_elements(p_items) loop
    qty := coalesce((item ->> 'quantity')::numeric, 0);
    cost_value := coalesce((item ->> 'unit_cost')::numeric, 0);
    if qty <= 0 or cost_value < 0 then raise exception 'بيانات المشتريات غير صحيحة'; end if;
    select * into product_row from public.pos_products
    where id = (item ->> 'product_id')::bigint and organization_id = org_id
    for update;
    if not found then raise exception 'المنتج غير موجود'; end if;
    insert into public.pos_purchase_items(organization_id, purchase_id, product_id, product_name, quantity, unit_cost)
    values (org_id, purchase_id, product_row.id, product_row.name, qty, cost_value);
    update public.pos_products set stock = stock + qty, cost = cost_value where id = product_row.id;
    insert into public.pos_stock_movements(organization_id, product_id, movement_type, quantity, reference_type, reference_id, created_by)
    values (org_id, product_row.id, 'purchase', qty, 'purchase', purchase_id, (select auth.uid()));
    subtotal_value := subtotal_value + (qty * cost_value);
  end loop;

  total_value := greatest(subtotal_value - greatest(coalesce(p_discount,0),0), 0);
  paid_value := least(greatest(coalesce(p_paid,0),0), total_value);
  invoice_no := 'NER-P-' || to_char(current_date, 'YYYYMMDD') || '-' || lpad(purchase_id::text, 6, '0');
  update public.pos_purchases set invoice_number = invoice_no, subtotal = subtotal_value, total = total_value, paid = paid_value where id = purchase_id;
  if p_supplier_id is not null then
    insert into public.pos_account_entries(organization_id, party_type, party_id, entry_type, direction, amount, currency, reference_type, reference_id, notes, created_by)
    values (org_id, 'supplier', p_supplier_id, 'purchase', 'credit', total_value, p_currency, 'purchase', purchase_id, invoice_no, (select auth.uid()));
    if paid_value > 0 then
      insert into public.pos_account_entries(organization_id, party_type, party_id, entry_type, direction, amount, currency, reference_type, reference_id, notes, created_by)
      values (org_id, 'supplier', p_supplier_id, 'purchase_payment', 'debit', paid_value, p_currency, 'purchase', purchase_id, invoice_no, (select auth.uid()));
    end if;
  end if;
  insert into public.pos_audit_logs(organization_id, user_id, action, entity_type, entity_id, details)
  values (org_id, (select auth.uid()), 'create_purchase', 'purchase', purchase_id, jsonb_build_object('invoice', invoice_no, 'total', total_value));
  return jsonb_build_object('id', purchase_id, 'invoice_number', invoice_no, 'total', total_value, 'paid', paid_value, 'due', total_value - paid_value);
end;
$$;

create or replace function public.pos_pay_installment(p_installment_id bigint, p_amount numeric, p_notes text default null)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  org_id bigint := (select private.current_pos_org_id());
  row_data public.pos_installments%rowtype;
  applied numeric(14,3);
  voucher_id bigint;
  voucher_no text;
  payment_currency text;
begin
  select * into row_data from public.pos_installments where id = p_installment_id and organization_id = org_id for update;
  if not found then raise exception 'القسط غير موجود'; end if;
  select currency into payment_currency from public.pos_sales where id = row_data.sale_id and organization_id = org_id;
  applied := least(greatest(coalesce(p_amount,0),0), row_data.amount - row_data.paid_amount);
  if applied <= 0 then raise exception 'المبلغ غير صحيح'; end if;
  update public.pos_installments set
    paid_amount = paid_amount + applied,
    paid_at = case when paid_amount + applied >= amount then now() else paid_at end,
    status = case when paid_amount + applied >= amount then 'paid' else 'partial' end,
    notes = coalesce(p_notes, notes)
  where id = row_data.id;
  insert into public.pos_vouchers(organization_id, voucher_type, party_type, party_id, amount, currency, notes, created_by)
  values (org_id, 'receipt', 'customer', row_data.customer_id, applied, coalesce(payment_currency, 'IQD'), coalesce(p_notes, 'تسديد قسط'), (select auth.uid()))
  returning id into voucher_id;
  voucher_no := 'NER-V-' || to_char(current_date, 'YYYYMMDD') || '-' || lpad(voucher_id::text, 6, '0');
  update public.pos_vouchers set voucher_number = voucher_no where id = voucher_id;
  insert into public.pos_account_entries(organization_id, party_type, party_id, entry_type, direction, amount, currency, reference_type, reference_id, notes, created_by)
  values (org_id, 'customer', row_data.customer_id, 'installment_payment', 'credit', applied, coalesce(payment_currency, 'IQD'), 'installment', row_data.id, voucher_no, (select auth.uid()));
  return jsonb_build_object('installment_id', row_data.id, 'amount', applied, 'voucher_number', voucher_no);
end;
$$;

create or replace function public.pos_reset_organization(confirm_text text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  org_id bigint := (select private.current_pos_org_id());
begin
  if org_id is null or not (select private.pos_has_role(array['owner'])) then raise exception 'المالك فقط يمكنه تصفير النظام'; end if;
  if confirm_text <> 'تصفير' then raise exception 'اكتب كلمة تصفير للتأكيد'; end if;
  delete from public.pos_audit_logs where organization_id = org_id;
  delete from public.pos_account_entries where organization_id = org_id;
  delete from public.pos_vouchers where organization_id = org_id;
  delete from public.pos_expenses where organization_id = org_id;
  delete from public.pos_installments where organization_id = org_id;
  delete from public.pos_stock_movements where organization_id = org_id;
  delete from public.pos_sale_items where organization_id = org_id;
  delete from public.pos_sales where organization_id = org_id;
  delete from public.pos_purchase_items where organization_id = org_id;
  delete from public.pos_purchases where organization_id = org_id;
  delete from public.pos_attendance where organization_id = org_id;
  delete from public.pos_payroll where organization_id = org_id;
  delete from public.pos_employees where organization_id = org_id;
  delete from public.pos_suppliers where organization_id = org_id;
  delete from public.pos_customers where organization_id = org_id;
  delete from public.pos_products where organization_id = org_id;
  insert into public.pos_audit_logs(organization_id, user_id, action, details)
  values (org_id, (select auth.uid()), 'system_reset', jsonb_build_object('at', now()));
  return true;
end;
$$;

