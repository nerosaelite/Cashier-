create or replace function public.pos_bootstrap_owner(company_name text default 'Nerosa Elite')
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  user_id uuid := (select auth.uid());
  org_id bigint;
  user_email text;
begin
  if user_id is null then raise exception 'يجب تسجيل الدخول'; end if;
  select organization_id into org_id from public.pos_profiles where pos_profiles.user_id = user_id;
  if org_id is not null then return org_id; end if;
  select email into user_email from auth.users where id = user_id;
  insert into public.pos_organizations(name) values (coalesce(nullif(trim(company_name), ''), 'Nerosa Elite')) returning id into org_id;
  insert into public.pos_profiles(user_id, organization_id, full_name, email, role)
  values (user_id, org_id, split_part(coalesce(user_email, ''), '@', 1), user_email, 'owner');
  return org_id;
end;
$$;
revoke all on function public.pos_bootstrap_owner(text) from public, anon;
grant execute on function public.pos_bootstrap_owner(text) to authenticated;

